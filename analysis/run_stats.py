"""Confirmatory + secondary statistics, exactly as preregistered.

  python analysis/run_stats.py --input data/confirmatory/episodes.csv

Writes data/confirmatory/results.json, data/confirmatory/results_tables.md and
data/failure_cases.json (worlds with the largest paired losses, for the GUI 'O' key)."""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
from stats_lib import holm, summarize_contrast  # noqa: E402

PRIMARY = [("H1", "P3", "A1", "ideal"), ("H2", "P3", "A2", "degraded")]
SECONDARY = [  # exploratory/secondary contrasts (no familywise claim)
    ("H1 (degraded comms)", "P3", "A1", "degraded"),
    ("H2 (ideal comms)", "P3", "A2", "ideal"),
    ("control ETA, naive beliefs: A2 - P2", "A2", "P2", "ideal"),
    ("control ETA, naive beliefs: A2 - P2", "A2", "P2", "degraded"),
    ("age-aware, graph ETA: A1 - P2", "A1", "P2", "degraded"),
    ("marginal vs selfish: P2 - P1", "P2", "P1", "ideal"),
    ("marginal vs selfish: P2 - P1", "P2", "P1", "degraded"),
    ("marginal vs greedy: P2 - P0", "P2", "P0", "ideal"),
    ("marginal vs greedy: P2 - P0", "P2", "P0", "degraded"),
    ("centralized reference: P4 - P3", "P4", "P3", "ideal"),
    ("centralized reference: P4 - P3", "P4", "P3", "degraded"),
    ("cost of degraded comms for P3", "P3", "P3", "degraded-ideal"),
]
OUTCOMES = ["welfare", "points", "completion_rate", "expired", "redundant_visits", "switches",
            "makespan", "distance", "energy", "collisions_boat", "collisions_obstacle",
            "near_misses", "mean_age_used", "cpu_ms_mean"]


def diffs(df, a, b, cond, outcome="welfare"):
    if cond == "degraded-ideal":
        x = df[df.policy == a].pivot_table(index="seed", columns="condition", values=outcome)
        return (x["degraded"] - x["ideal"]).dropna()
    x = df[df.condition == cond].pivot_table(index="seed", columns="policy", values=outcome)
    return (x[a] - x[b]).dropna()


def fmt_p(p):
    return f"{p:.2e}" if p < 1e-3 else f"{p:.4f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--input", default="data/confirmatory/episodes.csv")
    ap.add_argument("--n-perm", type=int, default=100_000)
    a = ap.parse_args()
    out_dir = os.path.dirname(a.input)
    df = pd.read_csv(a.input)
    # integrity checks
    n_worlds = df.seed.nunique()
    counts = df.groupby(["seed", "condition"]).policy.nunique()
    complete = bool((counts == df.policy.nunique()).all())
    res = dict(input=a.input, n_rows=len(df), n_worlds=n_worlds, design_complete=complete,
               config_hashes=sorted(df.config_hash.unique().tolist()), primary={}, secondary=[])
    prim = []
    for name, pa, pb, cond in PRIMARY:
        d = diffs(df, pa, pb, cond)
        s = summarize_contrast(d.to_numpy(), a.n_perm, seed=hash(name) % 1000)
        s.update(name=name, a=pa, b=pb, condition=cond)
        prim.append(s)
    adj = holm([s["p_perm"] for s in prim])
    for s, pa_ in zip(prim, adj):
        s["p_holm"] = float(pa_)
        s["reject_fwer_0.05"] = bool(pa_ < 0.05)
        res["primary"][s["name"]] = s
    for k, (name, pa, pb, cond) in enumerate(SECONDARY):
        d = diffs(df, pa, pb, cond)
        s = summarize_contrast(d.to_numpy(), 20_000, seed=100 + k)
        s.update(name=name, a=pa, b=pb, condition=cond)
        res["secondary"].append(s)
    # descriptive table per policy x condition (mean and 95% CI over worlds)
    desc = []
    for (cond, pol), g in df.groupby(["condition", "policy"]):
        row = dict(condition=cond, policy=pol)
        for o in OUTCOMES:
            v = g[o].dropna().to_numpy()
            row[o] = float(v.mean()) if len(v) else float("nan")
            row[o + "_se"] = float(v.std(ddof=1) / np.sqrt(len(v))) if len(v) > 1 else float("nan")
        desc.append(row)
    res["descriptive"] = desc
    # secondary outcomes for the primary contrasts
    res["primary_secondary_outcomes"] = {}
    for name, pa, pb, cond in PRIMARY:
        res["primary_secondary_outcomes"][name] = {
            o: dict(mean=float(diffs(df, pa, pb, cond, o).mean()),
                    sd=float(diffs(df, pa, pb, cond, o).std(ddof=1))) for o in OUTCOMES}
    json.dump(res, open(os.path.join(out_dir, "results.json"), "w"), indent=2, default=float)

    # markdown tables
    L = [f"# Confirmatory results (generated by analysis/run_stats.py)\n",
         f"Input `{a.input}`: {len(df)} episodes, {n_worlds} worlds, design complete: {complete}.\n",
         "## Primary family (Holm across H1, H2; two-sided sign-flip test, 100k permutations)\n",
         "| | contrast | comms | N | mean diff [95% BCa CI] | median [CI] | d_z [CI] | p (perm) | p (Holm) | reject at FWER .05 | worlds d>0 / d<0 / d=0 |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in prim:
        L.append(f"| {s['name']} | {s['a']} - {s['b']} | {s['condition']} | {s['n']} | "
                 f"{s['mean']:+.2f} [{s['ci_mean'][0]:+.2f}, {s['ci_mean'][1]:+.2f}] | "
                 f"{s['median']:+.2f} [{s['ci_median'][0]:+.2f}, {s['ci_median'][1]:+.2f}] | "
                 f"{s['dz']:+.3f} [{s['ci_dz'][0]:+.3f}, {s['ci_dz'][1]:+.3f}] | {fmt_p(s['p_perm'])} | "
                 f"{fmt_p(s['p_holm'])} | {'yes' if s['reject_fwer_0.05'] else 'no'} | "
                 f"{s['frac_positive']:.2f} / {s['frac_negative']:.2f} / {s['frac_zero']:.2f} |")
    L += ["", "Sensitivity (not used for decisions): " + "; ".join(
        f"{s['name']}: t-test p = {fmt_p(s['p_t'])}, Wilcoxon p = {fmt_p(s['p_wilcoxon'])}" for s in prim), "",
        "## Secondary / exploratory contrasts (unadjusted; 20k permutations; no familywise claim)\n",
        "| contrast | comms | N | mean diff [95% CI] | d_z | p (perm, unadjusted) |", "|---|---|---|---|---|---|"]
    for s in res["secondary"]:
        L.append(f"| {s['name']} | {s['condition']} | {s['n']} | {s['mean']:+.2f} "
                 f"[{s['ci_mean'][0]:+.2f}, {s['ci_mean'][1]:+.2f}] | {s['dz']:+.3f} | {fmt_p(s['p_perm'])} |")
    L += ["", "## Descriptive means per policy (± SE over worlds)\n",
          "| comms | policy | welfare | points | completion | expired | redundant | switches | energy | contacts (boat+obst) | CPU ms/decision |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(desc, key=lambda r: (r["condition"], r["policy"])):
        L.append(f"| {r['condition']} | {r['policy']} | {r['welfare']:.1f} ± {r['welfare_se']:.1f} | {r['points']:.1f} | "
                 f"{r['completion_rate']:.3f} | {r['expired']:.2f} | {r['redundant_visits']:.2f} | {r['switches']:.1f} | "
                 f"{r['energy']:.0f} | {r['collisions_boat'] + r['collisions_obstacle']:.2f} | {r['cpu_ms_mean']:.2f} |")
    open(os.path.join(out_dir, "results_tables.md"), "w").write("\n".join(L) + "\n")
    print("\n".join(L[:12]))

    # failure cases: worlds where P3 loses most to its comparators / to P4
    cases = []
    for name, pa, pb, cond in PRIMARY + [("P4 vs P3", "P3", "P4", "degraded")]:
        d = diffs(df, pa, pb, cond).sort_values()
        for seed, v in d.head(3).items():
            cases.append(dict(seed=int(seed), comm_mode=cond, policy_a=pb, policy_b=pa, n_boats=4,
                              diff=float(v), note=f"{name}: W({pa}) - W({pb}) = {v:+.1f}"))
    json.dump(cases, open("data/failure_cases.json", "w"), indent=2)


if __name__ == "__main__":
    main()
