"""Exploratory scaling summary: per fleet size, paired P4−P3 and P3−P2 (welfare per boat) and P3 fallback rate."""
import os, sys
import numpy as np, pandas as pd
sys.path.insert(0, os.path.dirname(__file__))
from stats_lib import bootstrap_ci
s = pd.read_csv("data/scale/episodes.csv")
s["n"] = s.condition.str.extract(r"n(\d+)_").astype(int); s["comm"] = s.condition.str.extract(r"_(\w+)$")
s["wpb"] = s.welfare / s.n_boats
rows = ["| fleet | comms | worlds | P4−P3 per boat [95% CI] | P3−P2 per boat [95% CI] | P3 points share | P4 points share | P3 episodes with ETA fallback |", "|---|---|---|---|---|---|---|---|"]
for (n, c), g in s.groupby(["n", "comm"]):
    x = g.pivot_table(index="seed", columns="policy", values="wpb")
    d1, d2 = (x.P4 - x.P3).dropna().to_numpy(), (x.P3 - x.P2).dropna().to_numpy()
    c1, c2 = bootstrap_ci(d1, B=4000), bootstrap_ci(d2, B=4000)
    fb = (g[g.policy == "P3"].fallbacks > 0).mean()
    ps = g.groupby("policy").points_frac.mean()
    rows.append(f"| {n} | {c} | {len(x)} | {d1.mean():+.2f} [{c1[0]:+.2f}, {c1[1]:+.2f}] | {d2.mean():+.2f} [{c2[0]:+.2f}, {c2[1]:+.2f}] | {ps['P3']:.3f} | {ps['P4']:.3f} | {100*fb:.0f}% |")
out = "# Scaling study (exploratory; generated by analysis/scale_summary.py)\n\nWelfare is divided by fleet size so sizes are comparable. Arena area and task count scale with fleet size (fixed density).\n\n" + "\n".join(rows) + "\n"
open("data/scale/scale_summary.md", "w").write(out); print(out)
